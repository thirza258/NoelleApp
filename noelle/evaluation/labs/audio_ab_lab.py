"""Audio A/B Listening Station and Subjective/Objective Evaluation.

Provides blind comparative evaluation where human evaluators audition audio
clips generated by competing providers (e.g. Local SpeechT5 vs. OpenAI TTS)
and record subjective scores alongside objective acoustic telemetry.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field

from noelle.providers.base import Modality, NodeRequest
from noelle.providers.registry import get_provider


@dataclass
class AudioCandidateResult:
    provider_id: str
    model_id: str
    audio_bytes: bytes
    latency_ms: float
    real_time_factor: float
    cost_usd: float
    audio_duration_s: float


@dataclass
class HumanEvaluationScore:
    candidate_id: str  # "A" or "B"
    naturalness: int   # 1-5
    pronunciation: int # 1-5
    intelligibility: int # 1-5
    emotion: int       # 1-5
    artifacts: int     # 1-5 (1 = clean, 5 = severe)
    preference_vote: str # "A", "B", or "same"
    notes: str = ""


@dataclass
class AudioABExperimentRecord:
    experiment_id: str
    text_prompt: str
    candidate_a: AudioCandidateResult
    candidate_b: AudioCandidateResult
    human_score: HumanEvaluationScore | None = None
    created_at: float = field(default_factory=time.time)


class AudioABLab:
    """Coordinates side-by-side synthesis and blind A/B auditing."""

    def synthesize_pair(self, text: str, provider_a: str, model_a: str,
                        provider_b: str, model_b: str) -> tuple[AudioCandidateResult, AudioCandidateResult]:
        """Synthesize audio from two competing engines under identical input text."""
        p_a = get_provider(provider_a)
        p_b = get_provider(provider_b)

        if p_a is None or p_b is None:
            raise RuntimeError(f"Providers must be registered: {provider_a}, {provider_b}")

        req_a = NodeRequest(modality=Modality.TTS, prompt=text, model=model_a)
        req_b = NodeRequest(modality=Modality.TTS, prompt=text, model=model_b)

        res_a = p_a.execute(req_a)
        res_b = p_b.execute(req_b)

        cand_a = AudioCandidateResult(
            provider_id=provider_a,
            model_id=model_a,
            audio_bytes=res_a.output if isinstance(res_a.output, bytes) else b"",
            latency_ms=res_a.telemetry.latency_ms,
            real_time_factor=res_a.telemetry.real_time_factor,
            cost_usd=res_a.telemetry.cost_usd,
            audio_duration_s=res_a.telemetry.audio_duration_s,
        )
        cand_b = AudioCandidateResult(
            provider_id=provider_b,
            model_id=model_b,
            audio_bytes=res_b.output if isinstance(res_b.output, bytes) else b"",
            latency_ms=res_b.telemetry.latency_ms,
            real_time_factor=res_b.telemetry.real_time_factor,
            cost_usd=res_b.telemetry.cost_usd,
            audio_duration_s=res_b.telemetry.audio_duration_s,
        )
        return cand_a, cand_b
